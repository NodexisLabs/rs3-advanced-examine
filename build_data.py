"""Build the Examine Data Lua files from the RuneScape Wiki.

Reads the wiki's drop, recipe, shop and game-id tables from the local
rswiki-mirror (./rswiki-mirror), joins them on wiki page names, and writes
compact Lua table modules that the plugin loads with require().

    python build_data.py            # build from the mirror as it is (no wiki requests)
    python build_data.py --refresh  # first update the mirror with pages changed on the wiki

This builder never talks to the wiki itself; the mirror owns every request and
its ledger (see rswiki-mirror/README.md).

Outputs (under plugin/data/):
    meta.lua                build date, licence, counts, chunk start indexes
    items.lua               item names + game Obj id -> item index
    sources.lua             drop sources (NPCs, scenery, openable items, ...)
                            + game NPC/Loc/Obj id -> source index
    rarities.lua            distinct rarity texts exactly as the wiki shows them
    drops/by_item_NN.lua    drop rows grouped by item   (lazy-loaded chunks)
    drops/by_source_NN.lua  drop rows grouped by source (lazy-loaded chunks)
    recipes.lua             recipes + madeBy / usedIn indexes
    shops.lua               current shop stock grouped by item
and build/report.md, which records every row that was dropped and why.

Wiki content is CC BY-NC-SA 3.0; the generated files carry that notice.
"""

import argparse
import datetime as dt
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "rswiki-mirror"))
from rswiki_mirror import Mirror, WikiError  # noqa: E402

CHUNK_TARGET_BYTES = 150_000   # drop chunks are cut near this size

ROOT = Path(__file__).resolve().parent
OUT_DIR = ROOT / "plugin" / "data"
BUILD_DIR = ROOT / "build"

LICENCE_HEADER = (
    "-- Generated by build_data.py from the RuneScape Wiki (https://runescape.wiki).\n"
    "-- Wiki content is licensed CC BY-NC-SA 3.0; this file is a derivative under the same licence.\n"
    "-- Do not edit by hand: rebuild instead.\n"
)

# Each wiki table we read, and the fields we need from it.
TABLES = {
    "dropsline": ["page_name", "item_name", "drop_json", "rare_drop_table"],
    "item_id": ["page_name", "page_name_sub", "id"],
    "npc_id": ["page_name", "page_name_sub", "id"],
    "object_id": ["page_name", "page_name_sub", "id"],
    "recipe": ["page_name", "production_json"],
    "storeline": ["page_name", "sold_item", "store_buy_price", "store_currency",
                  "store_stock", "store_stock_infinite", "is_historical", "is_members_only"],
}

# Drop flags, packed into one integer per row.
FLAG_APPROX = 1        # wiki marks the rate as approximate
FLAG_NOTED = 2         # dropped as banknotes
FLAG_RARE_TABLE = 4    # comes from the rare drop table


# --------------------------------------------------------------------------
# Reading from the mirror
# --------------------------------------------------------------------------
def load_tables(mirror):
    """Rows for every table this builder needs, plus when each was filled."""
    filled = dict(mirror.db.execute("SELECT bucket, filled_at FROM buckets"))
    data, fetched = {}, {}
    for table, fields in TABLES.items():
        data[table] = mirror.rows(table, fields)
        fetched[table] = filled.get(table)
        print(f"  {table}: {len(data[table])} rows (mirror filled {fetched[table]})")
    fetched["synced_to"] = mirror.synced_to()
    return data, fetched


# --------------------------------------------------------------------------
# Parsing helpers
# --------------------------------------------------------------------------
RATE_RE = re.compile(r"^~?\s*([\d.,]+)\s*/\s*([\d.,]+)$")


def parse_probability(rarity_text):
    """'1/128' -> 0.0078125, 'Always' -> 1.0, anything else -> None (unknown).

    Mirrors Rarity.probability in the plugin, which does the same parse at
    runtime; here it is only used to count unknown rates for the report.
    """
    text = rarity_text.strip()
    if text.lower() == "always":
        return 1.0
    m = RATE_RE.match(text)
    if not m:
        return None
    num = float(m.group(1).replace(",", ""))
    den = float(m.group(2).replace(",", ""))
    return num / den if den else None


def parse_number(value):
    """Wiki quantities arrive as int, float or text such as '1' or '1,000'."""
    if value is None or value == "":
        return None
    if isinstance(value, (int, float)):
        return value
    text = str(value).replace(",", "").strip()
    try:
        number = float(text)
    except ValueError:
        return None
    return int(number) if number.is_integer() else number


class Index:
    """Assigns 1-based Lua indexes to names in first-seen order."""

    def __init__(self):
        self.ids = {}

    def get(self, name):
        if name not in self.ids:
            self.ids[name] = len(self.ids) + 1
        return self.ids[name]

    def names(self):
        return list(self.ids)


# --------------------------------------------------------------------------
# Lua output
# --------------------------------------------------------------------------
def lua(value):
    """Serialise a Python value as a Lua literal."""
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return "%.6g" % value
    if isinstance(value, str):
        escaped = (value.replace("\\", "\\\\").replace('"', '\\"')
                   .replace("\n", "\\n").replace("\r", "\\r"))
        return f'"{escaped}"'
    if isinstance(value, (list, tuple)):
        return "{" + ",".join(lua(v) for v in value) + "}"
    raise TypeError(f"cannot serialise {type(value).__name__} to Lua")


def write_lua(path, columns_comment, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(LICENCE_HEADER + columns_comment + body, encoding="utf-8", newline="\n")
    return path.stat().st_size


def index_table(mapping):
    """{int -> value} as a Lua table literal, one entry per line."""
    return "{\n" + "".join(f"[{k}]={lua(v)},\n" for k, v in sorted(mapping.items())) + "}"


def write_chunks(prefix, groups, columns_comment):
    """Write {index -> rows} into files of roughly CHUNK_TARGET_BYTES each.

    Returns (sizes, starts): starts[n] is the first index stored in chunk n,
    so the plugin finds the chunk for index i by searching starts.
    """
    sizes, starts = {}, []
    current, current_bytes = [], 0

    def flush():
        nonlocal current, current_bytes
        if not current:
            return
        path = OUT_DIR / "drops" / f"{prefix}_{len(starts):02d}.lua"
        starts.append(int(current[0].split("]", 1)[0][1:]))
        sizes[path.name] = write_lua(path, columns_comment, "return {\n" + "".join(current) + "}\n")
        current, current_bytes = [], 0

    for key in sorted(groups):
        line = f"[{key}]={{" + ",".join(lua(r) for r in groups[key]) + "},\n"
        if current and current_bytes + len(line) > CHUNK_TARGET_BYTES:
            flush()
        current.append(line)
        current_bytes += len(line)
    flush()
    return sizes, starts


# --------------------------------------------------------------------------
# Build steps
# --------------------------------------------------------------------------
def build_name_to_ids(rows, report, label):
    """Wiki name -> set of game ids, from the item_id / npc_id / object_id tables.

    A versioned subpage such as "Super restore#(4)" is also stored under
    "Super restore (4)", the form drop tables use.
    """
    by_name = defaultdict(set)
    for row in rows:
        names = {row["page_name"]}
        page, _, anchor = (row.get("page_name_sub") or "").partition("#")
        if anchor:
            names.add(f"{page} {anchor}" if anchor.startswith("(") else f"{page} ({anchor})")
        for raw in row.get("id") or []:
            number = parse_number(raw)
            if not isinstance(number, int):
                report["dropped"][f"{label}: non-numeric id"] += 1
                continue
            for name in names:
                by_name[name].add(number)
    return by_name


def trim_defaults(row, defaults):
    """Drop trailing columns that hold their default value, to save space."""
    while len(row) > defaults[0] and row[-1] == defaults[1].get(len(row) - 1):
        row.pop()
    return row


# Row layout: {other, rarity, qtyLow, qtyHigh, flags, rolls}; flags=0 and
# rolls=1 are the defaults and are left off the end when possible.
ROW_DEFAULTS = (4, {4: 0, 5: 1})


def build_drops(rows, items, sources, rarities, report):
    by_item, by_source = defaultdict(list), defaultdict(list)
    seen = set()
    for row in rows:
        try:
            drop = json.loads(row["drop_json"])
        except (TypeError, json.JSONDecodeError):
            report["dropped"]["drop: unreadable drop_json"] += 1
            continue
        source, item = row.get("page_name"), row.get("item_name")
        if not source or not item:
            report["dropped"]["drop: missing source or item"] += 1
            continue
        rarity_text = str(drop.get("Rarity", "")).strip() or "Unknown"
        if rarity_text.lower() == "discontinued":
            report["dropped"]["drop: rarity 'discontinued'"] += 1
            continue
        low, high = parse_number(drop.get("Quantity Low")), parse_number(drop.get("Quantity High"))
        key = (source, item, rarity_text, low, high)
        if key in seen:
            report["dropped"]["drop: exact duplicate row"] += 1
            continue
        seen.add(key)

        if parse_probability(rarity_text) is None:
            report["rate_unknown"][rarity_text.lower()] += 1
        flags = 0
        if drop.get("Approx"):
            flags |= FLAG_APPROX
        if "noted" in str(drop.get("Drop Quantity", "")).lower():
            flags |= FLAG_NOTED
        if row.get("rare_drop_table"):
            flags |= FLAG_RARE_TABLE
        rolls = parse_number(drop.get("Rolls")) or 1

        s_idx, i_idx, r_idx = sources.get(source), items.get(item), rarities.get(rarity_text)
        tail = [r_idx, low, high, flags, rolls]
        by_item[i_idx].append(trim_defaults([s_idx] + tail, ROW_DEFAULTS))
        by_source[s_idx].append(trim_defaults([i_idx] + tail, ROW_DEFAULTS))
    report["counts"]["drop rows kept"] = sum(len(v) for v in by_item.values())
    return by_item, by_source


def build_recipes(rows, items, report):
    recipes, made_by, used_in = [], defaultdict(list), defaultdict(list)
    for row in rows:
        try:
            data = json.loads(row.get("production_json") or "")
        except json.JSONDecodeError:
            report["dropped"]["recipe: unreadable production_json"] += 1
            continue
        outputs = [[items.get(o["page"]), parse_number(o.get("quantity"))]
                   for o in data.get("outputs", []) if o.get("page")]
        materials = [[items.get(m["page"]), parse_number(m.get("quantity"))]
                     for m in data.get("materials", []) if m.get("page")]
        if not outputs:
            report["dropped"]["recipe: no outputs"] += 1
            continue
        skills = [[s.get("name"), parse_number(s.get("level")), parse_number(s.get("experience"))]
                  for s in data.get("skills", [])]
        recipes.append([outputs, materials, skills, parse_number(data.get("ticks")),
                        data.get("members") == "Yes"])
        r_idx = len(recipes)
        for item_idx, _ in outputs:
            made_by[item_idx].append(r_idx)
        for item_idx, _ in materials:
            used_in[item_idx].append(r_idx)
    report["counts"]["recipes kept"] = len(recipes)
    return recipes, made_by, used_in


def build_shops(rows, items, shops, currencies, report):
    by_item = defaultdict(list)
    for row in rows:
        if row.get("is_historical"):
            report["dropped"]["shop: historical listing"] += 1
            continue
        if not row.get("sold_item") or not row.get("page_name"):
            report["dropped"]["shop: missing shop or item"] += 1
            continue
        currency = (row.get("store_currency") or ["coins"])[0]
        stock = "infinite" if row.get("store_stock_infinite") else parse_number(row.get("store_stock"))
        by_item[items.get(row["sold_item"])].append([
            shops.get(row["page_name"]), parse_number(row.get("store_buy_price")),
            currencies.get(currency), stock, bool(row.get("is_members_only"))])
    report["counts"]["shop listings kept"] = sum(len(v) for v in by_item.values())
    return by_item


def game_id_map(names, name_to_ids):
    """{game id -> index} for the given names; the first name to claim an id wins."""
    result = {}
    for idx, name in enumerate(names, start=1):
        for game_id in sorted(name_to_ids.get(name, ())):
            result.setdefault(game_id, idx)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--refresh", action="store_true",
                        help="update the mirror with changed wiki pages first")
    args = parser.parse_args()

    mirror = Mirror()
    report = {"counts": Counter(), "dropped": Counter(), "rate_unknown": Counter(),
              "unmatched": {}}
    if args.refresh:
        print("Updating mirror")
        try:
            update = mirror.update()
        except WikiError as e:
            raise SystemExit(f"mirror update stopped: {e} | {mirror.ledger_summary()}")
        print(f"  {update['changed']} pages changed, {update['deleted']} deleted/moved")
        if update["templates"]:
            print(f"  WARNING: {len(update['templates'])} template/module edits; "
                  "consider `rswiki_mirror.py full <bucket>`")
    print("Loading tables from the mirror")
    data, fetched = load_tables(mirror)

    items, sources, rarities = Index(), Index(), Index()
    shops, currencies = Index(), Index()
    obj_ids = build_name_to_ids(data["item_id"], report, "item_id")
    npc_ids = build_name_to_ids(data["npc_id"], report, "npc_id")
    loc_ids = build_name_to_ids(data["object_id"], report, "object_id")

    drops_by_item, drops_by_source = build_drops(data["dropsline"], items, sources, rarities, report)
    recipes, made_by, used_in = build_recipes(data["recipe"], items, report)
    shop_stock = build_shops(data["storeline"], items, shops, currencies, report)

    # Joins that failed: names an in-game examine can never reach.
    item_names, source_names = items.names(), sources.names()
    report["unmatched"]["items"] = [n for n in item_names if n not in obj_ids]
    report["unmatched"]["drop sources"] = [
        n for n in source_names if n not in npc_ids and n not in loc_ids and n not in obj_ids]

    print("Writing Lua")
    # Everything under plugin/data is generated; clear it so no stale chunk survives.
    for old in OUT_DIR.rglob("*.lua") if OUT_DIR.exists() else []:
        old.unlink()
    sizes = {}
    row_cols = ("-- [%s] = {{%s, rarity, qtyLow, qtyHigh, flags=0, rolls=1}, ...}\n"
                "-- flags: 1 approximate rate, 2 noted, 4 rare drop table\n")
    chunk_sizes, item_starts = write_chunks("by_item", drops_by_item, row_cols % ("item", "source"))
    sizes.update(chunk_sizes)
    chunk_sizes, source_starts = write_chunks("by_source", drops_by_source, row_cols % ("source", "item"))
    sizes.update(chunk_sizes)

    by_obj = game_id_map(item_names, obj_ids)
    sizes["items.lua"] = write_lua(
        OUT_DIR / "items.lua",
        "-- names[i]: wiki page of item i; byObj[objId] = i\n",
        "return {\nnames=" + lua(item_names) + ",\nbyObj=" + index_table(by_obj) + ",\n}\n")

    source_by = {kind: game_id_map(source_names, ids)
                 for kind, ids in (("Npc", npc_ids), ("Loc", loc_ids), ("Obj", obj_ids))}
    sizes["sources.lua"] = write_lua(
        OUT_DIR / "sources.lua",
        "-- names[s]: wiki page of drop source s (an NPC, scenery, an openable item, ...)\n"
        "-- byNpc[npcId] / byLoc[locId] / byObj[objId] = s\n",
        "return {\nnames=" + lua(source_names) + ",\n" +
        "".join(f"by{kind}={index_table(m)},\n" for kind, m in source_by.items()) + "}\n")

    sizes["rarities.lua"] = write_lua(OUT_DIR / "rarities.lua",
                                      "-- rarity texts exactly as shown on the wiki\n",
                                      "return " + lua(rarities.names()) + "\n")
    sizes["recipes.lua"] = write_lua(
        OUT_DIR / "recipes.lua",
        "-- recipes[r]: {outputs {{item, qty}}, materials {{item, qty}}, skills {{name, level, xp}}, ticks, members}\n"
        "-- madeBy[item] / usedIn[item]: recipe indexes\n",
        "return {\nrecipes={\n" + "".join(lua(r) + ",\n" for r in recipes) + "},\n"
        "madeBy=" + index_table(made_by) + ",\nusedIn=" + index_table(used_in) + ",\n}\n")
    sizes["shops.lua"] = write_lua(
        OUT_DIR / "shops.lua",
        "-- stock[item]: {{shop, price, currency, stock, members}}\n",
        "return {\nshops=" + lua(shops.names()) + ",\ncurrencies=" + lua(currencies.names()) +
        ",\nstock=" + index_table(shop_stock) + ",\n}\n")

    built = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    counts = {"items": len(item_names), "sources": len(source_names),
              "itemsReachableInGame": len(item_names) - len(report["unmatched"]["items"]),
              "sourcesReachableInGame": len(source_names) - len(report["unmatched"]["drop sources"]),
              "dropRows": report["counts"]["drop rows kept"], "recipes": len(recipes),
              "shopListings": report["counts"]["shop listings kept"]}
    meta = ("return {\nbuilt=" + lua(built) + ",\nsource=\"RuneScape Wiki (runescape.wiki)\",\n"
            "licence=\"CC BY-NC-SA 3.0\",\n"
            "wikiFetched={" + ",".join(f"{k}={lua(v)}" for k, v in sorted(fetched.items())) + "},\n"
            "counts={" + ",".join(f"{k}={v}" for k, v in counts.items()) + "},\n"
            "chunkStarts={by_item=" + lua(item_starts) + ",by_source=" + lua(source_starts) + "},\n}\n")
    sizes["meta.lua"] = write_lua(OUT_DIR / "meta.lua", "", meta)

    write_report(report, counts, sizes, fetched, mirror)
    print(f"Wrote {len(sizes)} files, {sum(sizes.values()) / 1e6:.2f} MB total")
    for k, v in counts.items():
        print(f"  {k}: {v}")
    print(mirror.ledger_summary())


def write_report(report, counts, sizes, fetched, mirror):
    BUILD_DIR.mkdir(exist_ok=True)
    out = ["# Examine Data build report", "",
           f"Built {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')}", "",
           "## Counts", ""]
    out += [f"- {k}: {v}" for k, v in counts.items()]
    out += ["", "## Rows dropped, by reason", ""]
    out += [f"- {k}: {v}" for k, v in report["dropped"].most_common()] or ["- none"]
    out += ["", "## Drops with no numeric rate (kept, shown as text)", ""]
    out += [f"- {k}: {v}" for k, v in report["rate_unknown"].most_common()]
    for label, missing in report["unmatched"].items():
        out += ["", f"## {label.capitalize()} with no game id ({len(missing)})", "",
                "An in-game examine cannot reach these; they still appear as linked entries. First 40:", ""]
        out += [f"- {n}" for n in missing[:40]]
    out += ["", "## File sizes", ""]
    out += [f"- {name}: {size / 1e3:.0f} KB" for name, size in sorted(sizes.items())]
    out += [f"- total: {sum(sizes.values()) / 1e6:.2f} MB"]
    out += ["", "## Mirror fill times", ""]
    out += [f"- {t}: {when}" for t, when in sorted(fetched.items())]
    out += ["", "## API usage", "", "- " + mirror.ledger_summary()]
    (BUILD_DIR / "report.md").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
